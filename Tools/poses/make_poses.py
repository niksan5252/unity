def draw(name, head, torso, limbs, S=4):
    N = 400 * S
    im = Image.new("L", (N, N), 0); d = ImageDraw.Draw(im)
    def P(p): return (p[0] * S, p[1] * S)
    def line(a, b, w):
        d.line([P(a), P(b)], fill=255, width=w * S)
        for p in (a, b):
            q = P(p); r = w * S / 2; d.ellipse([q[0] - r, q[1] - r, q[0] + r, q[1] + r], fill=255)
    line(torso[0], torso[1], 70)
    for l in limbs:
        for a, b in zip(l, l[1:]): line(a, b, W)
    h = P(head); r = 36 * S; d.ellipse([h[0] - r, h[1] - r, h[0] + r, h[1] + r], fill=255)
    m = im.resize((512, 512), Image.LANCZOS)
    out = Image.new("RGBA", (512, 512), (0, 0, 0, 0))
    out.paste((20, 16, 30, 255), (0, 0), m)
    out.save(O + name + ".png")

for n, (h, t, l) in POSES.items(): draw(n, h, t, l)
